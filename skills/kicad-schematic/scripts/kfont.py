DESCENDERS = set("gjpqy_,;рудфцщзЗДЦЩ(){}[]|/")


def supported(ch):
    if ch == " ":
        return True
    cp = ord(ch)
    return any(a <= cp <= b for a, b in GLYPH_RANGES)


def unsupported_chars(text):
    """Символы строки, которых нет в шрифте KiCad (без повторов, по порядку)."""
    seen = []
    for ch in text:
        if not supported(ch) and ch not in seen:
            seen.append(ch)
    return seen


def ink_width(text, size=1.27):
    """Ширина чернил строки: от первого до последнего штриха."""
    if not text:
        return 0.0
    return max(0.0, sum(ADV.get(c, ADV_DEFAULT) for c in text) * size - TAIL * size)


def normalize(angle, justify):
    """Как KiCad показывает текст: никогда вверх ногами.

    Итоговый угол 180 превращается в 0, а 270 — в 90, и при этом выравнивание
    зеркалится (left <-> right). Для поля символа угол = угол символа + угол
    поля: поле с углом 0 у символа, повёрнутого на 90, стоит вертикально.
    Проверено по SVG KiCad 10.0.4.
    """
    a = int(angle) % 360
    j = justify or "center"
    if a in (180, 270):
        a -= 180
        j = {"left": "right", "right": "left"}.get(j, j)
    return a, j


# Вертикальные габариты чернил относительно точки привязки для кегля s:
# (верх, низ) без выносных элементов; снято по SVG.
def _vert(kind, s):
    if kind == "field":
        return (-0.5 * s - 0.056, 0.5 * s - 0.055)
    if kind == "text":
        return (-0.538 * s - 0.257, 0.463 * s - 0.259)
    if kind == "label":
        k = s / 1.27
        return (-1.783 * k, -0.513 * k)
    if kind == "glabel":
        k = s / 1.27
        return (-0.600 * k, 0.670 * k)
    raise ValueError(kind)


def _lead(kind, s):
    """Отступ чернил от точки привязки при выравнивании по краю."""
    if kind == "glabel":
        return 1.831 * s / 1.27
    return 0.099 + 0.2386 * s


def text_box(kind, text, at, size=1.27, angle=0, justify=None):
    """Габарит чернил надписи на листе: (x0, y0, x1, y1).

    kind: field | text | label | glabel. angle и justify — как записаны
    в файле (для поля — уже сложенные с углом символа); нормализация внутри.
    """
    x, y = at
    a, j = normalize(angle, justify)
    w = ink_width(text, size)
    top, bot = _vert(kind, size)
    if any(c in DESCENDERS for c in text):
        bot += 0.24 * size
    lead = _lead(kind, size)
    if j == "left":
        u0, u1 = lead, lead + w
    elif j == "right":
        u0, u1 = -lead - w, -lead
    else:
        u0, u1 = -w / 2, w / 2
    if a == 0:
        return (x + u0, y + top, x + u1, y + bot)
    # 90: текст читается снизу вверх; «вправо» по строке — это вверх по листу,
    # «верх» строки — влево по листу.
    return (x + top, y - u1, x + bot, y - u0)


def glabel_outline(text, at, size=1.27, angle=0):
    """Контур глобальной метки (рамка со стрелкой) — занимает больше текста."""
    x, y = at
    L = ink_width(text, size) + 4.161 * size / 1.27
    h = 1.27 * size / 1.27
    a = int(angle) % 360
    if a == 0:
        return (x, y - h, x + L, y + h)
    if a == 180:
        return (x - L, y - h, x, y + h)
    if a == 90:
        return (x - h, y - L, x + h, y)
    return (x - h, y, x + h, y + L)


